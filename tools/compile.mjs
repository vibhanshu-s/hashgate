// Compiles contracts/src with solc-js 0.8.24 for the Shanghai EVM (same settings as foundry.toml),
// writes contracts/out/<Name>.json and packages/sdk/src/abi.ts, and fails on Cancun-only opcodes.
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const require = createRequire(import.meta.url);
const solc = require("solc");
const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");

const sources = {};
function collect(dir, prefix) {
  for (const f of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, f.name);
    if (f.isDirectory()) collect(p, `${prefix}${f.name}/`);
    else if (f.name.endsWith(".sol")) sources[`${prefix}${f.name}`] = { content: readFileSync(p, "utf8") };
  }
}
collect(join(root, "contracts/src"), "src/");
const testMocks = join(root, "contracts/test/mocks");
try { collect(testMocks, "test/mocks/"); } catch {}

const input = {
  language: "Solidity",
  sources,
  settings: {
    evmVersion: "shanghai",
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors ?? []).filter((e) => e.severity === "error");
for (const e of out.errors ?? []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);

// Shanghai guard: MCOPY 0x5e, TLOAD 0x5c, TSTORE 0x5d, BLOBHASH 0x49, BLOBBASEFEE 0x4a
const BAD = new Set([0x5e, 0x5c, 0x5d, 0x49, 0x4a]);
function cancunOps(hex) {
  let b = Buffer.from(hex, "hex");
  // drop the CBOR metadata tail (its length is in the last 2 bytes)
  const metaLen = b.readUInt16BE(b.length - 2);
  b = b.subarray(0, b.length - 2 - metaLen);
  const found = [];
  for (let i = 0; i < b.length; i++) {
    const op = b[i];
    if (BAD.has(op)) found.push(op.toString(16));
    if (op >= 0x60 && op <= 0x7f) i += op - 0x5f; // skip PUSH data
  }
  return found;
}

mkdirSync(join(root, "contracts/out"), { recursive: true });
const abis = {};
for (const [file, contracts] of Object.entries(out.contracts)) {
  for (const [name, c] of Object.entries(contracts)) {
    const bytecode = c.evm.bytecode.object;
    if (!bytecode) continue;
    const bad = cancunOps(c.evm.deployedBytecode.object);
    if (bad.length) {
      console.error(`${name}: Cancun-only opcodes ${bad.join(",")} — Aevum runs Shanghai`);
      process.exit(1);
    }
    writeFileSync(join(root, "contracts/out", `${name}.json`), JSON.stringify({ abi: c.abi, bytecode: `0x${bytecode}` }, null, 1));
    if (file.startsWith("src/")) abis[name] = c.abi;
    console.log(`${name.padEnd(12)} ${(c.evm.deployedBytecode.object.length / 2).toString().padStart(6)} bytes  (${file})`);
  }
}
const ts = `// Generated by tools/compile.mjs. Do not edit.\n` +
  Object.entries(abis).filter(([n]) => ["Hashgate", "HashgateAccount", "HashgateAccountFactory", "HashgatePaymaster"].includes(n)).map(([n, a]) => `export const ${n[0].toLowerCase() + n.slice(1)}Abi = ${JSON.stringify(a, null, 2)} as const;\n`).join("\n");
writeFileSync(join(root, "packages/sdk/src/abi.ts"), ts);
